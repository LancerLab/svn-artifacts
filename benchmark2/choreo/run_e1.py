#!/usr/bin/env python3
"""E1 classifier for the choreo lane.

Takes the mutants written by gen_mutants.py and classifies each one into the
`mutant` record of schema/record-schema.json:

    outcome in {compile, runtime, never, n/a}
    stage   in {compile, runtime}
    manifest in {corrupts, noop}

Attribution — the part that is easy to get wrong
------------------------------------------------
A choreo kernel's `main()` already contains an independent host-side reference
check that calls `choreo::choreo_assert(...)`. That check is the ground-truth
ORACLE required by specs §7 — it is NOT choreo's detector.

There are FOUR distinct sources of assertion output, spread over TWO prefixes
and TWO streams. The prefix alone does not separate them, and neither does the
stream alone:

    "choreo runtime check failed: ..."   stderr   source A (host form)
                                                  AND source LIB (ungated)
    "choreo assertion failed: ..."       stdout   source A (device form),
                                                  source B, and source C

  A  generated ASSESSMENTS — **the assessor; an A firing is a detection.**
     `CreateAssessment` in lib/semacheck.cpp, emitted by
     `CuteCodeGen::EmitPreSiteAssertions` / `EmitPostSiteAssertions` at
     lib/Target/GPU/cute_codegen.cpp:11789 / :11801. Both begin
     `if (CCtx().DisableRuntimeCheck()) return;`, so A is GATED by
     --disable-runtime-check (equivalently -rtc=none). A has TWO emission forms,
     because per the comment at cute_codegen.cpp:11805 "HOIST_SITE and USE_SITE
     assertions are emitted in device code using choreo_assert (printf-based)
     because std::cerr is not available on device":
         A-host    runtime_check(...)  -> "choreo runtime check failed: " stderr
         A-device  choreo_assert(...)  -> "choreo assertion failed: "     stdout
     Both forms append the source location (`ar.message << ", " << ar.loc`), so
     A is identified by the suffix `, <path>:<line>.<col>` — see RE_ASSESSMENT.
     ONE gated family has no suffix and is matched separately: `shape
     inconsistent on the <ord> parameter (...)` (RE_SHAPE_CHECK). It is the
     commonest detection in this suite, so missing it is expensive.
     Do NOT enumerate A by message template: a template list only covers the
     assessments this semacheck version happens to create, and the location
     suffix is generated by the emitter itself, so it is complete by
     construction. A hand-written seven-template list previously matched ZERO
     lines across 160 real logs.
  B  runtime-LIBRARY bounds check. `ArrayProxy::operator[]` at
     runtime/choreo.h:394/405/782/791/884, message bare "Index out of bounds".
     NOT gated: verified by diffing a retained det.sh against its off.sh, which
     contain byte-identical call sites. B is a defensive container check, not
     assessor output, so it does NOT count as a detection.
  C  the §7 ORACLE. User-written `assert` BIF, passed through at
     cute_codegen.cpp:8359. Closed vocabulary — see RE_ORACLE_MSG.
  LIB runtime-HEADER sanity checks, ungated, and sharing A-host's prefix. Seven
     literals in runtime/choreo.h, all beginning `at::Tensor ` or `[choreo-rt]`:
     is undefined / must be a CUDA tensor / must be contiguous / rank mismatch /
     dtype mismatch / failed to allocate memory / failed to free memory.
     Matching the bare "choreo runtime check failed" prefix and calling it a
     detection would credit an OOM or a non-contiguous input tensor to the
     assessor, so RE_LIB_SANITY is tested BEFORE the prefix fallback.

Counting B, C or LIB as detected would inflate the detection matrix (S1) with
work that is not the assessor's. Conversely, matching C by NEGATION ("anything
that isn't template A1") silently absorbs A's other families as oracle-only and
records real detections as misses, which DEFLATES S2. Both classifiers here
therefore match A, B, C and LIB POSITIVELY and leave an `unattributed` bucket
for anything unrecognized, so a new message surfaces instead of being credited
to the harness.

B also fires from INSIDE the oracle arm, because the §7 comparison indexes its
own operands through ArrayProxy (`out[i][j][k]` at
benchmark/choreo/layer_normalization/1_bert_32x512x768_768_768.co:90,
`output[h][w][c]` at benchmark/choreo/softmax/common.hpp:70). That is why the
oracle arm records `oracle_caught` separately: a `manifest=corrupts` verdict
resting on B is not fully independent of choreo-provided code, and the record
should say so rather than hide it.

The oracle build
----------------
`-rtc=none` suppresses choreo's generated obligation checks (source A) while
leaving the kernel's own `choreo_assert` reference check (source C) and the
inlined runtime header's checks (source B and LIB) intact. Running the mutant
under `-rtc=none` is therefore exactly the specs §7 manifest check:

    oracle fails / aborts / no "Passed."  -> manifest = corrupts  (real defect)
    oracle prints "Passed."               -> manifest = noop      (discard, §11.1)

`-rtc=none` and `--disable-runtime-check` are EQUIVALENT, proven at the
generated-code level rather than assumed: over 20 mutants the two builds are
byte-identical after normalizing the `/tmp/<digits>_<digits>` staging directory.
Both reduce `runtime_check(` sites 14 -> 9 and leave `choreo_assert(` sites
39 -> 39 unchanged; the 5 removed sites are all `shape inconsistent on the Nth
parameter (...)`. So the flag removes only source A's host form and touches
neither source B nor source C. ORACLE_FLAGS keeps `-rtc=none`; the choice is
cosmetic, and the equivalence is now evidence rather than an assumption.

Usage:
  run_e1.py [--jobs N] [--limit N] [--only CLASS] [--out FILE]
"""

