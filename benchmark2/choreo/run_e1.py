def local_headers_for(category, suite_dir):
    """Non-.co files a category's kernels #include by bare relative path.

    choreo emits a .cu that does `#include "common.hpp"` and passes
    `-I<directory of the .co file>`, so the header must sit next to the kernel
    being compiled. Categories observed to need this: conv2d and transpose
    (common.h), matmul and softmax (common.hpp).
    """
    d = os.path.join(suite_dir, category)
    if not os.path.isdir(d):
        return []
    return [os.path.join(d, n) for n in sorted(os.listdir(d))
            if not n.endswith(".co") and os.path.isfile(os.path.join(d, n))]


def run(cmd, timeout, logpath, env=None):
    """Run cmd, tee combined output to logpath, return (rc, text).

    stdbuf -o0 -e0 is required: abort() discards buffered stdout, and the
    attribution message is printed on stdout immediately before the abort.
    """
    full = ["stdbuf", "-o0", "-e0"] + cmd
    e = dict(os.environ)
    if env:
        e.update(env)
    try:
        p = subprocess.run(full, capture_output=True, text=True,
                           timeout=timeout, cwd=REPO, errors="replace", env=e)
        text = (p.stdout or "") + (p.stderr or "")
        rc = p.returncode
    except subprocess.TimeoutExpired as ex:
        text = ((ex.stdout or b"").decode("utf-8", "replace") if isinstance(ex.stdout, bytes)
                else (ex.stdout or "")) + \
               ((ex.stderr or b"").decode("utf-8", "replace") if isinstance(ex.stderr, bytes)
                else (ex.stderr or ""))
        text += "\n[harness] TIMEOUT after %ds\n" % timeout
        rc = 124
    with open(logpath, "w") as f:
        f.write(text)
    return rc, text


def compile_stage(src, flags, out_sh, logpath):
    cmd = [CHOREO] + flags + [src, "-o", out_sh]
    rc, text = run(cmd, T_COMPILE, logpath)
    ok = rc == 0 and os.path.exists(out_sh) and os.path.getsize(out_sh) > 0
    return ok, rc, text


def execute_stage(out_sh, logpath, env=None):
    rc, text = run(["bash", out_sh, "--execute"], T_EXECUTE, logpath, env=env)
    return rc, text, infra_failure(text)


def classify_log(text, rc):
    """Return (caught_by, passed) for one execution log.

    `caught_by` is one of:
      detector        source A -- a choreo-generated assessment fired. Either the
                      entry-level `runtime_check` (stderr, before the body runs)
                      or a site `choreo_assert` (stdout, at the access). This is
                      the assessor's verdict and counts as DETECTED.
      runtime_lib     choreo-provided but NOT an assessor output: source B
                      (ArrayProxy's "Index out of bounds") or the ungated
                      `runtime_check` library sanity checks (`at::Tensor ...`,
                      `[choreo-rt] ...`). These survive
                      --disable-runtime-check, so they are present in the oracle
                      arm too and cannot evidence a static verdict. Counted as
                      NOT detected, but reported separately from the oracle so
                      the distinction stays visible.
      oracle          source C -- only the kernel's §7 reference check spoke.
                      NOT detected.
      unattributed    an assertion fired whose message matches none of the known
                      vocabularies. Deliberately NOT folded into `oracle`: doing
                      so would let an unrecognized choreo message silently count
                      as the harness's work. Needs a human look.
      crash           aborted with no attribution message (device-side trap)
      none            nothing fired

    Order matters, and the reason is that the sources share prefixes:
      1. Source A is matched FIRST and POSITIVELY (location suffix, or the
         `shape inconsistent` template). It must precede RE_RTC's bare prefix
         because A-host and the ungated library checks share that prefix.
      2. The library sanity checks are matched before the bare prefix, so an
         allocation failure is not credited to the assessor.
      3. Source B is anchored to end-of-line so it cannot match A's longer
         "Index <n> is out of bounds of the <ord> dimension of array ...,
         <path>:<line>.<col>" -- the two share a prefix but diverge after
         "bounds".
      4. Source C is matched positively from its closed vocabulary.
      5. Anything left that fired an assertion is `unattributed`.
    """
    assessment = bool(RE_ASSESSMENT.search(text))
    shape = bool(RE_SHAPE_CHECK.search(text))
    lib = bool(RE_LIB_SANITY.search(text))
    rtc = bool(RE_RTC.search(text))
    rtlib = bool(RE_RUNTIME_LIB.search(text))
    oracle = bool(RE_ORACLE_MSG.search(text))
    any_assert = bool(RE_ASSERT.search(text))
    passed = bool(RE_PASSED.search(text))

    if assessment or shape:
        # Source A. A guard firing means the access or the shape was wrong, so
        # the run cannot also have passed; if both markers are present the
        # assessment wins because it is the more specific evidence.
        return "detector", passed
    if lib:
        # Ungated library sanity check on the same prefix as A-host. choreo
        # shipped it but the assessor did not produce it.
        return "runtime_lib", passed
    if rtc:
        # A `runtime check failed` line that is neither a known assessment nor a
        # known library check. Do NOT assume it is an assessment: that is the
        # inference that credited allocation failures to the assessor. Surface
        # it instead.
        return "unattributed", passed
    if rtlib:
        return "runtime_lib", passed
    if oracle:
        return "oracle", passed
    if any_assert:
        # An assertion fired but matches no known vocabulary. Surface it rather
        # than guessing which mechanism to credit.
        return "unattributed", passed
    if passed:
        return "none", True
    return "crash" if rc not in (0,) else "none", passed


def classify_one(rec, workdir, keep_logs=True, policy=None):
    """Full E1 pipeline for one mutant. Returns a `mutant` record dict."""
    mid = rec["mutant_id"]
    src = os.path.join(REPO, rec["mutant_path"])
    d = os.path.join(workdir, mid.replace("/", "_"))
    os.makedirs(d, exist_ok=True)

    t0 = time.time()
    out = {
        "toolchain": TOOLCHAIN,
        "category": rec["category"],
        "class": rec["class"],
        "paper_category": rec["paper_category"],
        "mutant_id": mid,
        "level": str(rec["level"]),
        # cross-cutting provenance (statistics-manifest: non-negotiable)
        "settings_hash": rec.get("settings_hash"),
        "kernel_hash": rec.get("kernel_hash"),
        "mutant_hash": rec.get("mutant_hash"),
        "spec": rec["spec"],
        "case": rec["case"],
    }

    if not os.path.exists(src):
        out.update(outcome="n/a", stage="compile", manifest="noop",
                   note="mutant source missing")
        return out

    # Oracle configuration for this exact base case, from calibrate_oracle.py.
    # `use_check` is only true where the unmutated base was observed to PASS its
    # own reference check with -D__CHECK__; `oracle_usable` is false where the
    # base fails, in which case no manifest verdict can be trusted.
    pol = (policy or {}).get(f"{rec['category']}/{rec['case']}")
    if pol is None:
        # No calibration yet: fall back to the static gate list but say so.
        gated = rec["category"] in GATED_CHECK
        usable = True
        out["calibrated"] = False
    else:
        gated = pol["use_check"]
        usable = pol["oracle_usable"]
        out["calibrated"] = True
    out["check_flag"] = gated
    out["oracle_usable"] = usable
    xenv = {"EXTRA_TARGET_CFLAGS": "-D__CHECK__"} if gated else None

    # ---- 1. detector compile -------------------------------------------
    det_sh = os.path.join(d, "det.sh")
    ok, rc, _ = compile_stage(src, COMPILE_FLAGS, det_sh, os.path.join(d, "det.compile.log"))
    out["compile_rc"] = rc

    # ---- 2. oracle build (specs §7 manifest check) ----------------------
    # Done before the detector execute so that a compile-detected mutant still
    # gets a manifest verdict.
    off_sh = os.path.join(d, "off.sh")
    off_ok, off_rc, _ = compile_stage(src, ORACLE_FLAGS, off_sh,
                                      os.path.join(d, "off.compile.log"))
    out["oracle_compile_rc"] = off_rc

    manifest = "noop"
    oracle_note = ""
    infra = None
    if not off_ok:
        # The defect is visible even with obligation checks off: the program is
        # genuinely broken, so it corrupts.
        manifest = "corrupts"
        oracle_note = "oracle compile failed"
    else:
        orc, otext, infra = execute_stage(off_sh, os.path.join(d, "off.run.log"), env=xenv)
        out["oracle_run_rc"] = orc
        caught, passed = classify_log(otext, orc)
        out["oracle_passed"] = passed
        # Recorded separately because it changes what `manifest` means. The
        # manifest is supposed to be INDEPENDENT ground truth from the kernel's
        # own §7 reference check. Two ways that can fail, and they differ in
        # severity:
        #   detector    an ASSESSMENT fired despite --disable-runtime-check.
        #               Should be impossible (both emission sites early-return on
        #               DisableRuntimeCheck); if seen, the flag did not take and
        #               the whole oracle arm is suspect.
        #   runtime_lib ArrayProxy::operator[]'s bounds check fired. EXPECTED --
        #               source B is not gated, and the oracle reads its operands
        #               through ArrayProxy. It means "corrupts" rests partly on a
        #               choreo-provided bounds check, not purely on the harness's
        #               numeric comparison. Not an error, but a conflation a
        #               reader must be able to see rather than have folded away.
        out["oracle_caught"] = caught
        if passed and caught == "none" and orc == 0:
            manifest = "noop"
            oracle_note = "oracle passed: mutant does not corrupt output"
        else:
            manifest = "corrupts"
            oracle_note = f"oracle caught={caught} rc={orc}"
            if caught == "detector":
                oracle_note += (
                    "; ANOMALY: a choreo ASSESSMENT fired in the checks-off "
                    "oracle arm, so --disable-runtime-check did not suppress it "
                    "-- this manifest verdict is not independent of choreo")
            elif caught == "runtime_lib":
                oracle_note += (
                    "; choreo's runtime-library bounds check (ArrayProxy) fired "
                    "in the oracle arm -- expected, it is not gated by "
                    "--disable-runtime-check, but the verdict is then partly "
                    "choreo's rather than purely the harness's")
            elif caught == "unattributed":
                oracle_note += (
                    "; UNRECOGNIZED assertion message -- not matched to the "
                    "assessment, runtime-library, or §7 vocabularies; this "
                    "manifest verdict needs manual review")
    out["manifest"] = manifest
    out["oracle_note"] = oracle_note

    # ---- 3. detector verdict -------------------------------------------
    if not ok:
        out["outcome"] = "compile"
        out["stage"] = "compile"
        out["detector"] = "compile-error"
    else:
        drc, dtext, dinfra = execute_stage(det_sh, os.path.join(d, "det.run.log"), env=xenv)
        infra = infra or dinfra
        out["run_rc"] = drc
        caught, passed = classify_log(dtext, drc)
        out["detector"] = caught
        out["detector_passed"] = passed
        m = RE_EXECTIME.search(dtext)
        if m:
            out["exec_time_us"] = int(m.group(1))
        if caught == "detector":
            # A choreo-generated assessment fired: either the entry-level
            # `runtime_check` (stderr, before the body runs) or a site assertion
            # rendered from a semacheck template (stdout, at the access). Both
            # are the assessor's verdict, so both count as detected. Which of the
            # two spoke is recoverable from the run log if the entry/interior
            # split is ever needed.
            out["outcome"] = "runtime"
            out["stage"] = "runtime"
        else:
            # runtime_lib / oracle / unattributed / crash / clean pass: the
            # assessor did not speak, so choreo did not detect it. Note that
            # `runtime_lib` is choreo-provided code but is NOT an assessor
            # output -- it is an ungated defensive check in the container
            # accessor, present in the checks-off build too, so counting it as a
            # detection would credit the assessor with work the static analysis
            # never did. It stays distinguishable via the `detector` field.
            out["outcome"] = "never"
            out["stage"] = "runtime"

    if infra:
        # Verdict is untrustworthy: the program never ran to the point where a
        # detector could speak. Flag it loudly instead of reporting a number.
        out["infra_error"] = infra
        out["outcome"] = "n/a"
        out["note"] = f"infrastructure failure, verdict void: {infra}"
    elif not usable:
        # The base kernel fails its own reference check, so a mutant's failure
        # is not evidence of corruption. Detection verdicts are still valid
        # (choreo's obligation checks are independent of the reference), but the
        # manifest field cannot be decided. Mark it rather than guess.
        out["note"] = ("manifest undecidable: unmutated base fails its own "
                       "reference check (see raw/oracle_policy.json)")
        out["manifest"] = "noop"

    out["wall_s"] = round(time.time() - t0, 2)

    if not keep_logs:
        for f in os.listdir(d):
            if f.endswith(".log"):
                os.remove(os.path.join(d, f))
    out["log_dir"] = os.path.relpath(d, REPO)
    return out


def reproject_one(rec, workdir):
    """Re-derive the classifier-dependent fields of an EXISTING record from the
    retained run logs, without invoking choreo or nvcc.

    Why this exists. `classify_log` is the single place where a log becomes a
    verdict, and it has now been corrected twice. A full E1 re-run costs nvcc
    for 120 mutants x 2 arms (~12 s each) purely to re-read text that is already
    on disk under `raw/e1_logs/<mid>/`. Worse, it re-runs on a shared host, so
    it competes for CPU with whatever timing lane is measuring. Re-projection
    gets the same answer for free and, because the inputs are frozen, makes the
    before/after diff exact rather than confounded by a second execution.

    Only fields DERIVED FROM LOG TEXT are recomputed. Provenance (hashes, spec,
    case), build results (compile_rc, oracle_compile_rc, run_rc, oracle_run_rc)
    and the calibration policy are taken from the existing record as-is.
    """
    mid = rec["mutant_id"]
    d = os.path.join(workdir, mid.replace("/", "_"))
    out = dict(rec)
    out["reprojected"] = True

    def read(name):
        p = os.path.join(d, name)
        if not os.path.exists(p):
            return None
        with open(p, errors="replace") as f:
            return f.read()

    # ---- oracle arm ------------------------------------------------------
    # Mirrors classify_one's §7 block. `oracle_compile_rc != 0` short-circuits
    # to corrupts without a log, exactly as the original does.
    # `or 0` because a record written by an older harness may carry None, and
    # `None != 0` is True -- that would silently reclassify a clean oracle build
    # as "oracle compile failed".
    if (rec.get("oracle_compile_rc") or 0) != 0:
        manifest, note = "corrupts", "oracle compile failed"
    else:
        otext = read("off.run.log")
        if otext is None:
            out["reproject_error"] = "off.run.log missing; oracle arm not reprojected"
            return out
        orc = rec.get("oracle_run_rc", 0)
        caught, passed = classify_log(otext, orc)
        out["oracle_passed"] = passed
        out["oracle_caught"] = caught
        if passed and caught == "none" and orc == 0:
            manifest = "noop"
            note = "oracle passed: mutant does not corrupt output"
        else:
            manifest = "corrupts"
            note = f"oracle caught={caught} rc={orc}"
            if caught == "detector":
                note += ("; ANOMALY: a choreo ASSESSMENT fired in the checks-off "
                         "oracle arm, so --disable-runtime-check did not suppress "
                         "it -- this manifest verdict is not independent of choreo")
            elif caught == "runtime_lib":
                note += ("; choreo's runtime-library bounds check (ArrayProxy) "
                         "fired in the oracle arm -- expected, it is not gated by "
                         "--disable-runtime-check, but the verdict is then partly "
                         "choreo's rather than purely the harness's")
            elif caught == "unattributed":
                note += ("; UNRECOGNIZED assertion message -- not matched to the "
                         "assessment, runtime-library, or §7 vocabularies; this "
                         "manifest verdict needs manual review")

    # ---- detector arm ----------------------------------------------------
    if (rec.get("compile_rc") or 0) != 0:
        outcome, stage, detector = "compile", "compile", "compile-error"
    else:
        dtext = read("det.run.log")
        if dtext is None:
            out["reproject_error"] = "det.run.log missing; detector arm not reprojected"
            return out
        drc = rec.get("run_rc") or 0
        caught, passed = classify_log(dtext, drc)
        detector = caught
        out["detector_passed"] = passed
        if caught == "detector":
            outcome, stage = "runtime", "runtime"
        else:
            outcome, stage = "never", "runtime"

    # The `oracle_usable=False` override in classify_one wins over the arm
    # result: an unusable reference means no manifest verdict can be trusted.
    # Preserve it rather than silently re-deciding.
    if rec.get("oracle_usable") is False:
        manifest = "noop"
        out["note"] = rec.get("note") or (
            "manifest undecidable: unmutated base fails its own reference check "
            "(see raw/oracle_policy.json)")

    out["manifest"] = manifest
    out["oracle_note"] = note
    out["outcome"] = outcome
    out["stage"] = stage
    out["detector"] = detector
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--jobs", type=int, default=6,
                    help="parallel workers; E1 is a correctness lane so GPUs are "
                         "shared freely (manifest §6)")
    ap.add_argument("--limit", type=int, default=0)
    ap.add_argument("--only", default="", help="restrict to one class, e.g. M1")
    ap.add_argument("--manifest", default=MANIFEST_IN)
    ap.add_argument("--policy", default=ORACLE_POLICY)
    ap.add_argument("--out", default=os.path.join(RAW, "e1_mutant_records.json"))
    ap.add_argument("--workdir", default=os.path.join(RAW, "e1_logs"))
    ap.add_argument("--device", default=os.environ.get("CUDA_VISIBLE_DEVICES", "0"),
                    help="GPU index, recorded as gpu_device on every record "
                         "(schema requirement); E1 is a correctness lane so the "
                         "GPU is shared freely, exclusive=false")
    ap.add_argument("--no-logs", action="store_true")
    ap.add_argument("--reproject", action="store_true",
                    help="re-derive verdicts from the retained run logs under "
                         "--workdir instead of recompiling. Use after editing "
                         "classify_log: it costs no nvcc, does not disturb the "
                         "GPU, and makes the before/after diff exact. Reads the "
                         "existing --out file and rewrites it in place.")
    a = ap.parse_args()

    # MUST be absolute: run() executes choreo with cwd=REPO, so a relative
    # scratch path resolves against the repo root and choreo reports
    # "The input file ... does not exist" (rc=1) for every case.
    a.workdir = os.path.abspath(a.workdir)
    a.out = os.path.abspath(a.out)
    a.manifest = os.path.abspath(a.manifest)
    a.policy = os.path.abspath(a.policy)

    if not os.path.exists(CHOREO):
        print(f"ERROR: choreo binary not found at {CHOREO}", file=sys.stderr)
        print("       run `benchmark2/choreo/run.sh setup` first", file=sys.stderr)
        return 2

    data = json.load(open(a.manifest))
    recs = data["mutants"]
    if a.only:
        recs = [r for r in recs if r["class"] == a.only]
    if a.limit:
        recs = recs[:a.limit]

    os.makedirs(a.workdir, exist_ok=True)
    os.makedirs(os.path.dirname(a.out), exist_ok=True)
    # Print the full identity block (binary sha/mtime vs checkout HEAD) so a
    # stale-binary mismatch is visible in the run log, not just buried in the
    # records. `ver` is the binary's source commit — what the data actually came
    # from — which is what every record's toolchain_version must carry.
    idt = toolchain.describe()
    ver = idt["version"]

    policy = None
    if os.path.exists(a.policy):
        policy = json.load(open(a.policy))["policy"]
        bad = [k for k, v in policy.items() if not v["oracle_usable"]]
        print(f"[choreo] oracle policy: {len(policy)} cases, "
              f"{len(bad)} with an unusable reference")
    else:
        print(f"[choreo] WARNING: no {os.path.relpath(a.policy, REPO)} — run "
              f"calibrate_oracle.py first; manifest verdicts will be guesses",
              file=sys.stderr)

    print(f"[choreo] E1: classifying {len(recs)} mutants with {a.jobs} workers "
          f"(croqtile @ {ver or 'unknown'})")

    # ---- re-projection: no compile, no execute, no GPU -------------------
    if a.reproject:
        if not os.path.exists(a.out):
            print(f"ERROR: --reproject needs an existing record file at "
                  f"{os.path.relpath(a.out, REPO)}", file=sys.stderr)
            return 2
        prev = json.load(open(a.out))
        # The E1 artifact stores its rows under "records" (see the json.dump at
        # the end of main). Reading "results" here would find nothing, skip every
        # mutant, and then write a key collect.py has never heard of -- a silent
        # empty artifact. Accept both so a hand-edited file still works.
        if isinstance(prev, dict):
            prev_rows = prev.get("records") or prev.get("results") or []
        else:
            prev_rows = prev
        by_id = {r["mutant_id"]: r for r in prev_rows}
        results = []
        changed = collections.Counter()
        for r in recs:
            old = by_id.get(r["mutant_id"])
            if old is None:
                print(f"  [skip] {r['mutant_id']}: not in existing records",
                      file=sys.stderr)
                continue
            new = reproject_one(old, a.workdir)
            for f in ("outcome", "stage", "manifest", "detector", "oracle_caught"):
                if new.get(f) != old.get(f):
                    changed[f] += 1
                    print(f"  [DIFF] {new['mutant_id']:<26} {f}: "
                          f"{old.get(f)!r} -> {new.get(f)!r}")
            if new.get("reproject_error"):
                print(f"  [WARN] {new['mutant_id']}: {new['reproject_error']}",
                      file=sys.stderr)
            results.append(new)
        results.sort(key=lambda x: (x["class"], x["category"], x["mutant_id"]))
        # Preserve the original envelope (produced_by, elapsed_s, gpu_device,
        # exclusive, pinned_flags) so downstream readers see no schema drift, and
        # keep the row list under "records".
        payload = dict(prev) if isinstance(prev, dict) else {}
        payload.pop("results", None)
        payload.update({"toolchain": TOOLCHAIN, "toolchain_version": ver,
                        "toolchain_identity": idt, "records": results,
                        "reprojected": True})
        with open(a.out, "w") as f:
            json.dump(payload, f, indent=1)
        print(f"\n[choreo] reprojected {len(results)} records -> "
              f"{os.path.relpath(a.out, REPO)}")
        print(f"[choreo] field changes: {dict(changed) or 'NONE'}")
        return 0

    results = []
    t0 = time.time()
    with cf.ThreadPoolExecutor(max_workers=a.jobs) as ex:
        futs = {ex.submit(classify_one, r, a.workdir, not a.no_logs, policy): r
                for r in recs}
        for i, fut in enumerate(cf.as_completed(futs), 1):
            r = futs[fut]
            try:
                res = fut.result()
            except Exception as e:                      # keep the lane alive
                res = {"toolchain": TOOLCHAIN, "category": r["category"],
                       "class": r["class"], "paper_category": r["paper_category"],
                       "mutant_id": r["mutant_id"], "level": str(r["level"]),
                       "outcome": "n/a", "stage": "compile", "manifest": "noop",
                       "note": f"harness exception: {e!r}"}
            res["toolchain_version"] = ver
            # E1 is a correctness lane: manifest §6 lets it share the GPU, so
            # exclusive=false. No cost/residue/latency record is produced here.
            res["gpu_device"] = str(a.device)
            res["exclusive"] = False
            results.append(res)
            print(f"  [{i:>3}/{len(recs)}] {res['mutant_id']:<26} "
                  f"outcome={res['outcome']:<8} stage={res['stage']:<8} "
                  f"manifest={res['manifest']:<9} detector={res.get('detector','-')}",
                  flush=True)

    # stable order: class, then category, then mutant_id
    results.sort(key=lambda x: (x["class"], x["category"], x["mutant_id"]))
    with open(a.out, "w") as f:
        json.dump({"toolchain": TOOLCHAIN, "toolchain_version": ver,
                   "toolchain_identity": idt,
                   "produced_by": "minimal", "elapsed_s": round(time.time() - t0, 1),
                   "gpu_device": str(a.device), "exclusive": False,
                   "pinned_flags": {"compile": COMPILE_FLAGS,
                                    "oracle": ORACLE_FLAGS},
                   "records": results}, f, indent=1)

    # ---- report ---------------------------------------------------------
    print(f"\n[{choreo_tag()}] wrote {len(results)} records -> "
          f"{os.path.relpath(a.out, REPO)}  ({round(time.time()-t0,1)}s)")
    print(f"\n{'class':<6}{'compile':>9}{'runtime':>9}{'never':>7}{'n/a':>6}"
          f"{'corrupts':>10}{'noop':>6}")
    for cls in ("M1", "M2", "M3"):
        sub = [r for r in results if r["class"] == cls]
        c = collections.Counter(r["outcome"] for r in sub)
        mf = collections.Counter(r["manifest"] for r in sub)
        print(f"{cls:<6}{c['compile']:>9}{c['runtime']:>9}{c['never']:>7}"
              f"{c['n/a']:>6}{mf['corrupts']:>10}{mf['noop']:>6}")
    tot = collections.Counter(r["outcome"] for r in results)
    mft = collections.Counter(r["manifest"] for r in results)
    print(f"{'ALL':<6}{tot['compile']:>9}{tot['runtime']:>9}{tot['never']:>7}"
          f"{tot['n/a']:>6}{mft['corrupts']:>10}{mft['noop']:>6}")

    noops = [r["mutant_id"] for r in results if r["manifest"] == "noop"]
    if noops:
        print(f"\nDISCARD (manifest=noop, specs §11.1): {len(noops)}")
        for m in noops:
            print(f"  {m}")

    infra = [r for r in results if r.get("infra_error")]
    if infra:
        print(f"\nINFRASTRUCTURE FAILURES (verdicts void, fix the harness): "
              f"{len(infra)}")
        for r in infra:
            print(f"  {r['mutant_id']:<26} {r['infra_error']}")
    # S2 sanity: choreo detects every mutant before the device is reached.
    before_device = tot["compile"] + tot["runtime"]
    print(f"\nS2 (before-device detections): {before_device}/{len(results)}"
          f"   never={tot['never']}")
    if tot["never"]:
        print("  never-detected mutants (oracle caught them, choreo did not):")
        for r in results:
            if r["outcome"] == "never":
                print(f"    {r['mutant_id']:<26} {r['class']}/{r['category']:<22}"
                      f" detector={r.get('detector')}")
    return 0


def choreo_tag():
    return "choreo"


if __name__ == "__main__":
    sys.exit(main())
