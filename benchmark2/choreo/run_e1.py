# ---------------------------------------------------------------------------
# THREE sources of assertion output, split across TWO prefixes and TWO streams.
# ---------------------------------------------------------------------------
# This was gotten wrong once already, in a way that looked right. The first
# model said all three sources print "choreo assertion failed" on stdout and
# that only the message text separates them. Measured against the 160 retained
# raw/e1_logs/*/*.run.log files that is false, so here is what the logs and the
# codegen actually say.
#
#   A. GENERATED ASSESSMENTS -- the assessor, the paper's mechanism, and the
#      only source that evidences a static-analysis verdict. GATED: both
#      emission sites in CuteCodeGen::Emit{Pre,Post}SiteAssertions
#      (cute_codegen.cpp:11789/11801) begin `if (CCtx().DisableRuntimeCheck())
#      return;`. A has TWO emission forms, and which one you get depends on
#      whether the site is host or device code:
#
#        A-host   `choreo::runtime_check(...)`  -> STDERR, prefix
#                 "choreo runtime check failed: "
#        A-device `choreo::choreo_assert(...)`   -> STDOUT, prefix
#                 "choreo assertion failed: "
#
#      The device form exists because, per the comment at cute_codegen.cpp:11805,
#      "HOIST_SITE and USE_SITE assertions are emitted in device code using
#      choreo_assert (printf-based) because std::cerr is not available on
#      device." Both forms append the source location into the message
#      (`ar.message << ", " << ar.loc`), so both end with `, <path>:<line>.<col>`.
#
#      In the E1 default-flag corpus only A-host occurs: 16 "runtime check
#      failed" lines, all in the det arm, zero in the off arm, and zero
#      "assertion failed" lines carrying a location suffix. A-device is NOT
#      hypothetical, though -- it is what the forced-flag probe produces. Under
#      `-rtc=all --disable-assert-hoist`, 8 of the 37 `never` mutants fire
#      A-device on stdout with the suffix intact, e.g.
#        /tmp/.../choreo.h:221: choreo assertion failed: The 1st index ` (k - 1) `
#        of element access 'bias' should be greater than or equal to 0,
#        /tmp/never_8bd25ddf/k.co:34.102
#      Both matchers are therefore load-bearing, just on different corpora.
#
#   B. RUNTIME-LIBRARY BOUNDS CHECK -- ArrayProxy::operator[] in
#      runtime/choreo.h:394/405/782/791/884, message is the bare literal
#      "Index out of bounds", stdout, NO location suffix. NOT gated: verified by
#      counting call sites in the retained scripts (M2.s4.ln1.caller.out
#      det.sh=12 off.sh=12; M2.s1.ln1.caller.scale det.sh=12 off.sh=12). This
#      is a defensive check inside the container accessor, not assessor output.
#
#   C. §7 ORACLE -- user-written `assert` BIF calls in benchmark/choreo, passed
#      through at cute_codegen.cpp:8359. stdout, NO location suffix. NOT gated.
#      The harness's own numeric reference check: ground truth, never a
#      detection.
#
# WHY THE LOCATION SUFFIX, NOT A TEMPLATE LIST, IDENTIFIES A ON STDOUT.
# An earlier version of this file enumerated seven message templates read off
# the CreateAssessment call sites (semacheck.cpp:449, 605-634, 1035, 1090,
# 1996-2004, 863; gpu_adapt.hpp:675) and matched them against the
# "choreo assertion failed" prefix. That regex matched ZERO lines in 160 logs,
# for two independent reasons: the templates are emitted under the runtime_check
# prefix, not the assertion prefix; and one of the seven was wrong anyway (the
# DMA template renders `'from'(` with no space before the paren). A template
# list is also inherently incomplete -- it can only cover assessments this
# version of semacheck happens to create. The location suffix is generated by
# the emitter itself (`<< ", " << ar.loc`) and so is present for EVERY
# assessment regardless of which template produced it. Match on that.
#
# WHY B MUST NOT BE FOLDED INTO C. The oracle reads its own operands through
# ArrayProxy (`out[i][j][k]`, layer_normalization/1_bert:90; `output[h][w][c]`,
# softmax/common.hpp:70), so a mutated index can trip source B from INSIDE the
# oracle arm. A negative-lookahead matcher ("anything that is not A is oracle")
# silently absorbs those as oracle-only, which both (i) hides that the manifest
# verdict was not independent of choreo, and (ii) mislabels a choreo-provided
# bounds check as the harness's work. B therefore gets its own label. Measured:
# 4 oracle-arm rows in this suite rest on B.
#
# WHY A MUST NOT BE FOLDED INTO C EITHER. Without it a mutant whose assessment
# fires is recorded detector="oracle", outcome="never" -- choreo charged with
# missing a bug it caught. Measured consequence at -rtc=all
# --disable-assert-hoist: 8 of the 37 `never` mutants fire an assessment (see
# raw/c2_probe_groundtruth.json), so S2 is configuration-dependent and the
# default-level figure understates the assessor.
#
# THOSE 8 ARE NOT ONE PHENOMENON. Comparing the hoist_on and hoist_off arms of
# the forced-flag probe separates two mechanisms that the single-flag-set
# fixture conflates:
#   (a) 2 mutants fire in BOTH arms -> recovered by `-rtc=all` alone. The
#       assessment was simply never EMITTED at the default check level. This is
#       an emission-policy consequence, working as designed.
#       M1.s3.ln1.bias, M1.s3.ln3.bias.
#   (b) 6 mutants fire only with `--disable-assert-hoist` -> the assessment WAS
#       emitted but placed where it cannot fire. This is a genuine codegen
#       HOISTING DEFECT, and it is fixable.
#       M1.s1.ln3.mask, M1.s2.ln1.out, M1.s2.ln1.scale, M1.s2.ln3.scale,
#       M1.s5.ln1.chunk, M2.s4.ln1.out.
# All 8 are layer_normalization (7 M1 + M2.s4.ln1.out). Set (b) matches the
# HOISTING_DEFECT promotions in raw/never_attribution.json exactly (6/6).
# Reporting all 8 as "policy" would understate a real bug by 6 detections.
#
# The location suffix is the discriminator for source A on either prefix.
RE_ASSESSMENT = re.compile(
    r"choreo (?:runtime check|assertion) failed: .*\.co:\d+\.\d+\s*$",
    re.MULTILINE,
)
# A SECOND source-A family carries NO location suffix, so RE_ASSESSMENT does not
# see it: `shape inconsistent on the <ord> parameter ('<name>', dim: <n>):
# expect: <n>, but got <n>.` It is emitted via runtime_check at
# cute_codegen.cpp:9965+ and is nonetheless GATED -- measured on 20 mutants, a
# base build has 5 such sites and a --disable-runtime-check build has 0. In this
# suite it is the commonest detection of all: 10 of the 16 source-A log lines.
RE_SHAPE_CHECK = re.compile(
    r"choreo runtime check failed: shape inconsistent on the \w+ parameter \("
)
# UNGATED LIBRARY SANITY CHECKS. These share source A's host prefix
# ("choreo runtime check failed: ") but are NOT assessments: they live in
# runtime/choreo.h, survive --disable-runtime-check, and report harness or
# allocator faults rather than a static-analysis verdict. The complete closed set
# (`grep -rhoE 'runtime_check\([^;]{0,220}' runtime/ | grep -oE '"[^"]{3,90}'`,
# cross-checked by diffing base vs --disable-runtime-check codegen over 20
# mutants) is seven literals, all beginning `at::Tensor ` or `[choreo-rt]`:
#   at::Tensor is undefined.          at::Tensor must be a CUDA tensor.
#   at::Tensor must be contiguous.    at::Tensor rank mismatch: expect ...
#   at::Tensor dtype mismatch.        [choreo-rt] failed to allocate memory.
#   [choreo-rt] failed to free memory.
# Matching the bare prefix and calling it a detection -- which is what an
# earlier version of this file did -- would credit an allocation failure or a
# non-contiguous input tensor to the assessor. No such line occurs in the 160
# retained logs, so this is a latent bug rather than a measured error, but it is
# the same defect as the negative-lookahead oracle matcher and gets the same
# treatment: enumerate positively.
RE_LIB_SANITY = re.compile(
    r"choreo runtime check failed: (?:at::Tensor |\[choreo-rt\])"
)
# Source B: bare literal, no trailing detail. Anchored so it cannot match an
# assessment's "Index <n> is out of bounds of the <ord> dimension of array ...,
# <path>:<line>.<col>" -- the two share a prefix but B has no location suffix.
RE_RUNTIME_LIB = re.compile(r"choreo assertion failed: Index out of bounds\s*$",
                            re.MULTILINE)
# Source C: the closed vocabulary of hand-written §7 checks, enumerated from the
# suite (`grep -rho 'choreo_assert([^;]*' benchmark/choreo | grep -o '"[^"]*"'`):
#   85 "values are not equal."   21 "concat mismatch"   19 "batch_norm mismatch"
#   16 "reduce_mean mismatch"     4 "error"              2 "Test Failed"
#    1 "actual != expect"         1 "sampled verification failed"
# Matched POSITIVELY rather than as "not A and not B", because a negative
# matcher turns any unrecognized message into an oracle verdict -- the one
# direction that inflates the harness and deflates choreo. An unmatched message
# falls through to `unattributed` below so it is visible instead of absorbed.
RE_ORACLE_MSG = re.compile(
    r"choreo assertion failed: (?:"
    r"values are not equal\.|concat mismatch|batch_norm mismatch"
    r"|reduce_mean mismatch|Test Failed|actual != expect"
    r"|sampled verification failed|error"
    r")"
)
# Success markers. The suite is NOT consistent about these; all six spellings
# below occur in benchmark/choreo (counts from `grep -rhoE '"[^"]*[Pp]ass[^"]*"'`):
#
#   146  "Passed.\n"            hand-written main(), most categories
#     9  "Test %s Passed!\n"    matmul common.hpp TEST2/TEST3
#     7  " is PASS.\n"          transpose, conv2d-style main()
#     4  "Test %s passed!\n"    softmax common.hpp TEST1/TEST2  (lowercase p)
#     1  "Test Passed\n"
#     1  "Case %s Passed!\n"    matmul common.hpp TEST1
#
# Matching only "Passed." silently marked every transpose base as failing its
# own reference check, which would have voided 10 mutants' manifest verdicts.
RE_PASSED = re.compile(
    r"^Passed\.$"
    r"|^(?:Test|Case)\b.*\bpassed!?$"
    r"|^Test Passed$"
    r"|^.*\bis PASS\.$",
    re.M | re.I)
RE_EXECTIME = re.compile(r"Execution time:\s*(\d+)\s*(?:us|microseconds)")

# Infrastructure failures. These mean the harness could not build or launch the
# program at all, so they carry NO information about detection and must never be
# folded into outcome=never (that would silently corrupt the S1 matrix).
RE_INFRA = re.compile(
    r"fatal error: .*No such file or directory"
    r"|\.exe: No such file or directory"
    r"|cannot find -l"
    r"|CUDA_HOME|CUTE_HOME"
    r"|\[harness\] TIMEOUT"
    r"|No space left on device"
    r"|cudaErrorInsufficientDriver"
    r"|no CUDA-capable device is detected"
)


def infra_failure(text):
    """Return a short reason if the log shows a harness/environment fault."""
    m = RE_INFRA.search(text)
    return m.group(0)[:120] if m else None


def sha1_12(path):
    import hashlib
    with open(path, "rb") as f:
        return hashlib.sha1(f.read()).hexdigest()[:12]


