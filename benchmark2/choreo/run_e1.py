# Categories whose reference check is compiled out unless -D__CHECK__ is given
# (their common.h/common.hpp wraps the cpu_* comparison in `#ifdef __CHECK__`).
# Without this the oracle silently does nothing and every mutant looks like a
# clean pass -> false `noop`. The generated script forwards EXTRA_TARGET_CFLAGS
# into nvcc, so that is how the flag is delivered.
#
# __CHECK__ is enabled for BOTH builds on purpose: the detector build then runs
# choreo's obligation checks *and* the oracle, the oracle build runs only the
# oracle, and the difference is attributable to choreo alone. choreo's entry
# checks fire before any computation, so they cannot be masked by the oracle.
#
# Whether the flag is actually used is decided per (category, case) by
# --calibrate, because some built-in references are themselves wrong (measured:
# the UNMUTATED softmax base aborts with "choreo assertion failed: Test Failed",
# so its cpu_softmax1 reference disagrees with the kernel's own layout). Enabling
# __CHECK__ there would mark every mutant `corrupts` regardless of the defect.
